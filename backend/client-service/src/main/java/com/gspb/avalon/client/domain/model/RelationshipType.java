package com.gspb.avalon.client.domain.model;

/**
 * Enumeration of possible relationship types.
 */
public enum RelationshipType {
    /**
     * Spouse relationship.
     */
    SPOUSE,
    
    /**
     * Child relationship.
     */
    CHILD,
    
    /**
     * Parent relationship.
     */
    PARENT,
    
    /**
     * Sibling relationship.
     */
    SIBLING,
    
    /**
     * Business partner relationship.
     */
    BUSINESS_PARTNER,
    
    /**
     * Authorized representative relationship.
     */
    AUTHORIZED_REPRESENTATIVE,
    
    /**
     * Beneficiary relationship.
     */
    BENEFICIARY,
    
    /**
     * Other relationship type.
     */
    OTHER
}
