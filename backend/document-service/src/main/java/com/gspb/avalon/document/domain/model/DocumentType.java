package com.gspb.avalon.document.domain.model;

/**
 * Enumeration of possible document types in the system.
 */
public enum DocumentType {
    /**
     * Loan agreement document.
     */
    LOAN_AGREEMENT,
    
    /**
     * Collateral agreement document.
     */
    COLLATERAL_AGREEMENT,
    
    /**
     * Term sheet document.
     */
    TERM_SHEET,
    
    /**
     * Disclosure document.
     */
    DISCLOSURE,
    
    /**
     * Promissory note document.
     */
    PROMISSORY_NOTE,
    
    /**
     * Amortization schedule document.
     */
    AMORTIZATION_SCHEDULE,
    
    /**
     * KYC document.
     */
    KYC_DOCUMENT,
    
    /**
     * Collateral valuation document.
     */
    COLLATERAL_VALUATION,
    
    /**
     * Approval document.
     */
    APPROVAL_DOCUMENT,
    
    /**
     * Other document.
     */
    OTHER
}
